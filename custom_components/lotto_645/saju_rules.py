PRINCIPAL = {branch: max(hidden, key=hidden.get) for branch, hidden in HIDDEN.items()}
TEN_GODS = ("비견", "겁재", "식신", "상관", "편재", "정재", "편관", "정관", "편인", "정인")
STEM_HARMONY = {"甲己": "earth", "乙庚": "metal", "丙辛": "water", "丁壬": "wood", "戊癸": "fire"}
