SIX_HARMONY = {"子丑": "earth", "寅亥": "wood", "卯戌": "fire", "辰酉": "metal", "巳申": "water", "午未": None}
BRANCH_CLASH = ("子午", "丑未", "寅申", "卯酉", "辰戌", "巳亥")
BRANCH_BREAK = ("子酉", "午卯", "寅亥", "申巳", "辰丑", "戌未")
